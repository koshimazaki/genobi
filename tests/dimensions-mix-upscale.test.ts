import { describe, expect, it } from "vitest";
import { regenerateMessage } from "../shared/director/regenerate";
import { dimensionsMix } from "../shared/templates/dimensions-mix";
import {
  mixUpscaleLine,
  mixUpscaleStep,
} from "../shared/templates/mix-upscale";
import { tierOf } from "../shared/templates/plan";
import type { HouseTemplate } from "../shared/templates/types";

// The Dimensions mix's optional last step: SeedVR2 on the rendered cut. It
// is declared, offered and described; nothing in the template runs it.
const withUpscaler = (entry: string): HouseTemplate => ({
  ...dimensionsMix,
  mix: {
    ...dimensionsMix.mix!,
    upscale: { ...dimensionsMix.mix!.upscale!, entry },
  },
});

describe("the Dimensions mix's upscale step", () => {
  it("offers SeedVR2 at 2×, opt-in, and the tier stays Open", () => {
    expect(dimensionsMix.run).toBe("mix");
    expect(dimensionsMix.mix!.upscale).toEqual({
      entry: "seedvr2-upscale",
      factor: 2,
      optIn: true,
    });
    const step = mixUpscaleStep(dimensionsMix)!;
    expect(step.label).toBe("Upscale with SeedVR2 (open)");
    expect(step.entry.open).toBe(true);
    expect(dimensionsMix.tier).toBe("open");
    expect(tierOf(dimensionsMix)).toBe("open");
    // Nothing is generated by opening the mix: still no shots to price.
    expect(dimensionsMix.shots).toEqual([]);
  });

  it("would cost the Open tier if the step named a closed upscaler", () => {
    expect(tierOf(withUpscaler("flux-video-upscale"))).toBe("semi-open");
  });

  it("refuses a step that is not a ready upscaler, out of range or automatic", () => {
    expect(() => mixUpscaleStep(withUpscaler("flux-3-klein"))).toThrow(
      /not a ready upscaler/,
    );
    const step = dimensionsMix.mix!.upscale!;
    expect(() =>
      mixUpscaleStep({
        ...dimensionsMix,
        mix: { ...dimensionsMix.mix!, upscale: { ...step, factor: 4 } },
      }),
    ).toThrow(/outside/);
    expect(() =>
      mixUpscaleStep({
        ...dimensionsMix,
        mix: {
          ...dimensionsMix.mix!,
          upscale: { ...step, optIn: false as unknown as true },
        },
      }),
    ).toThrow(/opt-in/);
  });

  it("tells an agent the step is optional and must be quoted and approved", () => {
    const line = mixUpscaleLine(mixUpscaleStep(dimensionsMix)!);
    expect(line).toMatch(/only if the person asks/);
    expect(line).toMatch(/genobi_quote/);
    expect(line).toMatch(/never start it on your own/);
    const message = regenerateMessage({
      instruction: "Tighten bar 3.",
      project: {
        id: "dimensions-mix",
        name: "Dimensions mix",
        revision: 1,
        layers: [],
      } as never,
      feedback: { commands: [], notes: [], unmapped: [] } as never,
      optionalStep: line,
    });
    expect(message).toContain("seedvr2-upscale");
    expect(
      regenerateMessage({
        instruction: "Tighten bar 3.",
        project: {
          id: "x",
          name: "x",
          revision: 1,
          layers: [],
        } as never,
        feedback: { commands: [], notes: [], unmapped: [] } as never,
      }),
    ).not.toContain("seedvr2");
  });
});
