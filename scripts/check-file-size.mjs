// Fails when a tracked source file grows past 500 lines, the repository's
// file-size rule (AGENTS.md, "Rules that matter"). It reads `git ls-files`, so
// untracked output and dependencies are never measured.
//
// Markdown is reported, not enforced: plans and verification records grow with
// what they record, and `npm run check:wiki` already holds docs to tags,
// summaries and working links. A long page is listed so it can be split by
// topic when it next changes.
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";

const LIMIT = 500;
const SOURCE = new Set([
  "ts",
  "tsx",
  "mts",
  "cts",
  "js",
  "jsx",
  "mjs",
  "cjs",
  "css",
  "py",
  "html",
  "sh",
  "yml",
  "yaml",
  "sql",
]);
const REPORTED = new Set(["md"]);

// Every exception is named here with its reason. A generated file has no
// limit; a hand-written one may carry `max` (at most ~800) only when splitting
// would genuinely hurt cohesion, and the reason must say why.
const ALLOWED = new Map([
  ["worker/env.d.ts", { reason: "Generated by `wrangler types`." }],
  [
    "src/director/generated-validators.mjs",
    { reason: "Generated by `npm run director:validators`." },
  ],
  [
    "public/motion/text-generation/text-image-generation.js",
    {
      max: 800,
      reason:
        "Vendored Transitions.dev file kept byte for byte (licence and provenance; its sha256 is pinned in tests/genobi-teaser.test.ts), so it cannot be split.",
    },
  ],
]);

const extension = (file) => {
  const name = file.slice(file.lastIndexOf("/") + 1);
  const dot = name.lastIndexOf(".");
  return dot > 0 ? name.slice(dot + 1).toLowerCase() : "";
};

/** Lines as `wc -l` counts them, plus a last line with no newline. */
const countLines = (bytes) => {
  let lines = 0;
  for (const byte of bytes) if (byte === 10) lines++;
  return bytes.length && bytes[bytes.length - 1] !== 10 ? lines + 1 : lines;
};

const tracked = execFileSync("git", ["ls-files", "-z"], { encoding: "utf8" })
  .split("\0")
  .filter(Boolean);

const failures = [];
const reports = [];
let measured = 0;
for (const file of tracked) {
  const kind = extension(file);
  const enforced = SOURCE.has(kind);
  if (!enforced && !REPORTED.has(kind)) continue;
  let bytes;
  try {
    bytes = await readFile(file);
  } catch (error) {
    // Deleted in the working tree but still in the index: nothing to measure.
    if (error.code === "ENOENT") continue;
    throw error;
  }
  // Binary content is never source, whatever its extension says.
  if (bytes.includes(0)) continue;
  measured++;
  const lines = countLines(bytes);
  const allowed = ALLOWED.get(file);
  const limit = allowed ? (allowed.max ?? Infinity) : LIMIT;
  if (lines <= limit) continue;
  (enforced ? failures : reports).push({ file, lines, limit });
}

const describe = ({ file, lines, limit }) => `  ${file}: ${lines} > ${limit}`;
if (reports.length) {
  console.log(`Long Markdown pages (reported, not enforced):`);
  for (const report of reports) console.log(describe(report));
}
if (failures.length) {
  console.error(
    `Files over the ${LIMIT}-line limit (${failures.length}). Split them by ` +
      `topic, or name a justified exception in scripts/check-file-size.mjs:`,
  );
  for (const failure of failures) console.error(describe(failure));
  process.exit(1);
}
console.log(
  `File size check passed: ${measured} tracked text files, none over ${LIMIT} lines outside the allowlist.`,
);
