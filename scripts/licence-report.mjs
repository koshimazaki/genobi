// Write LICENCES-npm.md: every package `npm ci --omit=dev` installs, with the
// licence its package.json declares, read from package-lock.json so the report
// matches the committed tree exactly. `--check` writes nothing and fails when
// the report is stale, a licence is missing, or a licence is not allowed below.
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

const root = new URL("../", import.meta.url);
const target = new URL("LICENCES-npm.md", root);

// Licences any shipped package may carry. Each one lets us bundle and
// redistribute the code, commercially, with its notice kept.
const allowed = new Map([
  ["MIT", "permissive"],
  ["ISC", "permissive"],
  ["0BSD", "permissive"],
  ["BSD-2-Clause", "permissive"],
  ["BSD-3-Clause", "permissive"],
  ["Apache-2.0", "permissive; keep its NOTICE"],
  ["Zlib", "permissive"],
  // SGI Free Software License B 2.0: X11-style permissive terms (libtess).
  ["SGI-B-2.0", "permissive"],
  // Font licence: the fonts may be bundled and used, not sold on their own.
  ["OFL-1.1", "fonts only"],
]);

// Copyleft packages accepted one by one, with the licence they had when
// reviewed. A new version that changes its licence fails again. GPL, AGPL and
// anything not listed here or above stay out of shipped code.
const exceptions = new Map([
  [
    "p5",
    {
      licence: "LGPL-2.1",
      reason:
        "Weak copyleft, accepted: bundled unmodified into the Director browser code. A change to p5 itself must be published under LGPL-2.1; see LICENCES.md.",
    },
  ],
  [
    "mediabunny",
    {
      licence: "MPL-2.0",
      reason:
        "File-level copyleft, accepted: bundled unmodified for MP4 decoding and export. A change to its files must be published under MPL-2.0.",
    },
  ],
]);

/** Parse a flat or parenthesised SPDX expression into a tree of AND/OR. */
function parse(expression) {
  const tokens = expression.match(/\(|\)|[^\s()]+/g) ?? [];
  let i = 0;
  const term = () => {
    if (tokens[i] === "(") {
      i++;
      const inner = or();
      i++; // ")"
      return inner;
    }
    return { id: tokens[i++] };
  };
  const and = () => {
    const parts = [term()];
    while (tokens[i] === "AND") {
      i++;
      parts.push(term());
    }
    return parts.length === 1 ? parts[0] : { and: parts };
  };
  const or = () => {
    const parts = [and()];
    while (tokens[i] === "OR") {
      i++;
      parts.push(and());
    }
    return parts.length === 1 ? parts[0] : { or: parts };
  };
  return or();
}

const permitted = (node) =>
  node.id
    ? allowed.has(node.id)
    : node.and
      ? node.and.every(permitted)
      : node.or.some(permitted);

const lock = JSON.parse(await readFile(new URL("package-lock.json", root)));
const direct = new Set(Object.keys(lock.packages[""].dependencies ?? {}));
const rows = [];
const problems = [];
for (const [path, meta] of Object.entries(lock.packages)) {
  // Dev-only packages never reach the browser bundle, server or MCP bundle.
  // `devOptional` and `optional` ones can install with --omit=dev, so they stay.
  if (!path || meta.dev) continue;
  const name = meta.name ?? path.slice(path.lastIndexOf("node_modules/") + 13);
  const licence = typeof meta.license === "string" ? meta.license.trim() : "";
  const exception = exceptions.get(name);
  let note = "";
  if (!licence) problems.push(`${name}@${meta.version}: no licence declared`);
  else if (exception && exception.licence === licence) note = exception.reason;
  else if (!permitted(parse(licence)))
    problems.push(`${name}@${meta.version}: ${licence} is not allowed`);
  rows.push({
    name,
    version: meta.version,
    licence: licence || "UNKNOWN",
    kind: direct.has(name) && path === `node_modules/${name}` ? "direct" : "",
    optional: meta.optional || meta.devOptional ? "optional" : "",
    note,
  });
}
rows.sort((a, b) =>
  a.name === b.name
    ? a.version.localeCompare(b.version)
    : a.name.localeCompare(b.name),
);

const counts = new Map();
for (const row of rows)
  counts.set(row.licence, (counts.get(row.licence) ?? 0) + 1);
const cell = (text) => text.replaceAll("|", "\\|");
const markdown = `# npm dependency licences

Generated by \`npm run licences\` from \`package-lock.json\`. Do not edit by
hand. \`npm run check:licences\` (also in CI) fails when this file is stale, a
package declares no licence, or a licence is outside the allowlist in
[\`scripts/licence-report.mjs\`](scripts/licence-report.mjs).

It lists the ${rows.length} packages a production install
(\`npm ci --omit=dev\`) can contain: what the browser bundle, the local server,
the Worker and the MCP bundle draw from. Build and test tools are left out. The
licence is the one each package's own \`package.json\` declares; full texts
ship in each package, and the MCP bundle carries its own in
[\`plugins/genobi/server/THIRD_PARTY_LICENSES.txt\`](plugins/genobi/server/THIRD_PARTY_LICENSES.txt).
Models, software and assets are in [LICENCES.md](LICENCES.md).

## By licence

| Licence | Packages |
| --- | --- |
${[...counts]
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
  .map(([licence, count]) => `| ${cell(licence)} | ${count} |`)
  .join("\n")}

## Packages

| Package | Version | Licence | Direct | Optional | Note |
| --- | --- | --- | --- | --- | --- |
${rows
  .map(
    (r) =>
      `| \`${r.name}\` | ${r.version} | ${cell(r.licence)} | ${r.kind ? "yes" : ""} | ${r.optional ? "yes" : ""} | ${cell(r.note)} |`,
  )
  .join("\n")}
`;
const report = await format(markdown, { parser: "markdown" });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch {
    // A missing report is stale.
  }
  if (current !== report)
    problems.push("LICENCES-npm.md is stale. Run npm run licences.");
} else await writeFile(target, report);

if (problems.length) {
  console.error(`Licence check failed:\n- ${problems.join("\n- ")}`);
  process.exit(1);
}
console.log(`Licence check passed: ${rows.length} production packages.`);
