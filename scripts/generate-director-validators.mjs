import { readFile, writeFile } from "node:fs/promises";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { format } from "prettier";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const json = async (path) =>
  JSON.parse(await readFile(new URL(path, root), "utf8"));
const ajv = new Ajv({
  allErrors: true,
  allowUnionTypes: true,
  code: { source: true },
});
for (const name of ["layers", "resources", "project"])
  ajv.addSchema(await json(`docs/director-bundle/schema/${name}.schema.json`));
const project = await json("docs/director-bundle/schema/project.schema.json");
const registry = await json("docs/director-bundle/example/studio.json");
const effects = await json("docs/director-bundle/effects/project.json");
const exports = { project: project.$id };
for (const module of [
  ...Object.values(registry.modules),
  ...Object.values(effects.modules),
]) {
  const name = `module_${module.file.sha256}`;
  ajv.addSchema(module.parameterSchema, name);
  exports[name] = name;
}
// Bundle AJV's CommonJS runtime helper into a browser-native ESM module.
const bundled = await build({
  stdin: {
    contents: standaloneCode(ajv, exports),
    sourcefile: "validators.cjs",
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  // Name modules by the path under the repository, not a symlink's target,
  // so a worktree whose node_modules is a link generates the same file.
  preserveSymlinks: true,
});
const code = await format(
  "// Generated by scripts/generate-director-validators.mjs. No runtime eval.\n" +
    bundled.outputFiles[0].text,
  { parser: "babel" },
);
const target = new URL("src/director/generated-validators.mjs", root);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== code)
    throw new Error(
      "Director validators are stale. Run npm run director:validators.",
    );
  console.log("Director standalone validators match their schemas.");
} else await writeFile(target, code);
